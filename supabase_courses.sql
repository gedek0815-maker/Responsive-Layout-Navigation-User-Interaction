-- Tahap 11: Membuat Tabel Database courses pada Supabase
-- Jalankan skrip ini pada SQL Editor di Dashboard Supabase project Anda.

-- 1. Buat Tabel courses (Poin 64, 66, 67, 68)
CREATE TABLE IF NOT EXISTS courses (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code TEXT NOT NULL,
    title TEXT NOT NULL,
    credits INT NOT NULL,
    status TEXT NOT NULL CHECK (status IN ('planned', 'active', 'done')),
    created_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL
);

-- 2. Konfigurasi RLS (Row Level Security) (Poin 69 & 70)
-- Aktifkan RLS
ALTER TABLE courses ENABLE ROW LEVEL SECURITY;

-- Catatan (Poin 70): Policy permisif ini HANYA untuk kebutuhan laboratorium praktikum.
-- Kebijakan ini mengizinkan akses SELECT, INSERT, UPDATE, DELETE ke anon key.
CREATE POLICY "Allow public read access" 
ON courses FOR SELECT 
TO anon 
USING (true);

CREATE POLICY "Allow public insert access" 
ON courses FOR INSERT 
TO anon 
WITH CHECK (true);

CREATE POLICY "Allow public update access" 
ON courses FOR UPDATE 
TO anon 
USING (true);

CREATE POLICY "Allow public delete access" 
ON courses FOR DELETE 
TO anon 
USING (true);

